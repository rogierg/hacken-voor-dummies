def get_text(key, lang='nl', **kwargs):
    """Get translated text for a key in the specified language"""
    text = TRANSLATIONS.get(lang, TRANSLATIONS['nl']).get(key, key)
    # Support string formatting like {emoji}
    if kwargs:
        text = text.format(**kwargs)
    return text

def get_all(lang='nl'):
    """Get all translations for a language"""
    return TRANSLATIONS.get(lang, TRANSLATIONS['nl'])
